/* =============================================
   PhD Timeline Gantt - Application Logic
   =============================================
   Reads data.json (generated by convert_timeline.py
   and auto-updated by GitHub Actions) and renders
   an interactive Gantt chart.
   ============================================= */

(function () {
  'use strict';

  var MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  // ---- DOM references ----
  var $ = function(sel) { return document.querySelector(sel); };

  var dom = {
    loadingOverlay: $('#loading-overlay'),
    errorOverlay: $('#error-overlay'),
    errorMessage: $('#error-message'),
    retryBtn: $('#retry-btn'),
    app: $('#app'),
    headerStats: $('#header-stats'),
    keyDates: $('#key-dates'),
    phaseFilter: $('#phase-filter'),
    statusFilter: $('#status-filter'),
    typeFilter: $('#type-filter'),
    ownerFilter: $('#owner-filter'),
    taskPanelBody: $('#task-panel-body'),
    timelineHeader: $('#timeline-header'),
    timelineBody: $('#timeline-body'),
    tooltip: $('#tooltip'),
    refreshBtn: $('#refresh-btn'),
    lastRefresh: $('#last-refresh'),
  };

  // ---- State ----
  var allTasks = [];
  var enrolmentDate = null;
  var keyDatesData = [];
  var phases = [];

  // ---- Utility functions ----

  function addMonths(date, n) {
    var d = new Date(date);
    d.setMonth(d.getMonth() + n);
    return d;
  }

  function fmtDate(d) {
    if (!d) return '-';
    return d.getDate() + ' ' + MONTH_NAMES[d.getMonth()] + ' ' + d.getFullYear();
  }

  function relativeTime(d) {
    if (!d) return '';
    var now = new Date();
    var diffMs = d - now;
    var diffDays = Math.round(diffMs / 86400000);
    if (diffDays < 0) return Math.abs(diffDays) + ' days ago';
    if (diffDays === 0) return 'today';
    if (diffDays < 30) return 'in ' + diffDays + ' days';
    var diffMonths = Math.round(diffDays / 30.44);
    if (diffMonths < 12) return 'in ' + diffMonths + ' month' + (diffMonths > 1 ? 's' : '');
    var diffYears = (diffDays / 365.25).toFixed(1);
    return 'in ~' + diffYears + ' years';
  }

  function daysBetween(a, b) {
    return Math.round((b - a) / 86400000);
  }

  function isDueLessThanOneMonth(endDate) {
    if (!endDate) return false;
    var now = new Date();
    var diff = endDate - now;
    return diff < 30 * 86400000;
  }

  function getHighlightClass(task) {
    var status = (task.status || '').toLowerCase().trim();
    if (status === 'done') return 'highlight-done';
    if (status === 'not started' && task.startDate && new Date() >= task.startDate) return 'highlight-overdue-not-started';
    var urgent = isDueLessThanOneMonth(task.endDate);
    if (!urgent) return '';
    if (status === 'in progress') return 'highlight-urgent-progress';
    if (status === 'not started') return 'highlight-urgent-not-started';
    if (status === 'delayed') return 'highlight-urgent-delayed';
    return '';
  }

  function getBarClass(task) {
    var status = (task.status || '').toLowerCase().trim();
    if (status === 'done') return 'bar-done';
    var urgent = isDueLessThanOneMonth(task.endDate);
    if (status === 'not started' && task.startDate && new Date() >= task.startDate) return 'bar-overdue-not-started';
    if (urgent && status === 'in progress') return 'bar-urgent-progress';
    if (urgent && status === 'not started') return 'bar-urgent-not-started';
    if (urgent && status === 'delayed') return 'bar-urgent-delayed';
    return 'bar-default';
  }

  function statusBadge(status) {
    var s = (status || '').toLowerCase().trim();
    var cls = s === 'done' ? 'done'
      : s === 'in progress' ? 'in-progress'
        : s === 'delayed' ? 'delayed'
          : 'not-started';
    var label = s === 'in progress' ? 'In Progress'
      : s === 'not started' ? 'Not Started'
        : status;
    return '<span class="status-badge ' + cls + '">' + label + '</span>';
  }

  function typeBadge(type) {
    var t = (type || '').toLowerCase().trim();
    var cls = t === 'milestone' ? 'milestone' : 'task';
    return '<span class="type-badge ' + cls + '">' + type + '</span>';
  }

  function phaseIndex(phaseName) {
    var idx = phases.indexOf(phaseName);
    return idx >= 0 ? idx % 5 : 0;
  }

  function isSharedOwner(owner) {
    if (!owner) return false;
    var lower = owner.toLowerCase().trim();
    return lower !== 'me' && lower !== 'saya';
  }

  // ---- Data loading (data.json only - fast, no OneDrive) ----

  async function loadData() {
    var resp = await fetch('data.json');
    if (!resp.ok) {
      throw new Error(
        'Could not load data.json. Please run convert_timeline.py to generate it, then push to GitHub.'
      );
    }
    var data = await resp.json();
    enrolmentDate = new Date(data.enrolmentDate);
    allTasks = data.tasks.map(function(t) {
      return Object.assign({}, t, {
        startDate: t.startDate ? new Date(t.startDate) : null,
        endDate: t.endDate ? new Date(t.endDate) : null,
      });
    });
    keyDatesData = (data.keyDates || []).map(function(kd) {
      return Object.assign({}, kd, {
        date: kd.date ? new Date(kd.date) : null,
      });
    });
  }

  // ---- Rendering ----

  function getDateXPos(date, monthCols, monthW) {
    if (!date) return 0;
    for (var i = 0; i < monthCols.length; i++) {
      var colDate = monthCols[i].date;
      var nextDate = i + 1 < monthCols.length ? monthCols[i + 1].date : addMonths(colDate, 1);
      if (date >= colDate && date < nextDate) {
        var totalMs = nextDate - colDate;
        var elapsedMs = date - colDate;
        var frac = totalMs > 0 ? elapsedMs / totalMs : 0;
        return (i + frac) * monthW;
      }
    }
    if (date >= monthCols[monthCols.length - 1].date) {
      return monthCols.length * monthW;
    }
    return 0;
  }

  function computeMonthColumns() {
    if (!enrolmentDate) return [];
    var cols = [];
    var startMonth = new Date(enrolmentDate.getFullYear(), enrolmentDate.getMonth(), 1);
    for (var m = 0; m < 46; m++) {
      var d = new Date(startMonth.getFullYear(), startMonth.getMonth() + m, 1);
      cols.push({
        month: d.getMonth(),
        year: d.getFullYear(),
        date: d,
        monthNum: m + 1,
        label: MONTH_NAMES[d.getMonth()],
        yearLabel: String(d.getFullYear()).slice(-2),
      });
    }
    return cols;
  }

  function render() {
    var filteredTasks = getFilteredTasks();
    var monthCols = computeMonthColumns();
    var now = new Date();
    var currentMonthIdx = monthCols.findIndex(function(c) {
      return c.month === now.getMonth() && c.year === now.getFullYear();
    });
    renderStats();
    renderKeyDates();
    renderTimelineHeader(monthCols, currentMonthIdx);
    renderTasksAndBars(filteredTasks, monthCols, currentMonthIdx);
    renderTodayLine(monthCols);
  }

  function getSelectedValues(multiSelectEl) {
    var checkboxes = multiSelectEl.querySelectorAll('input[type="checkbox"]');
    var values = [];
    checkboxes.forEach(function(cb) {
      if (cb.checked && cb.value !== '__all__') values.push(cb.value);
    });
    return values;
  }

  function updateMultiSelectLabel(multiSelectEl, allLabel) {
    var checkboxes = multiSelectEl.querySelectorAll('input[type="checkbox"]');
    var totalOptions = 0;
    checkboxes.forEach(function(cb) { if (cb.value !== '__all__') totalOptions++; });
    
    var selected = getSelectedValues(multiSelectEl);
    var labelEl = multiSelectEl.querySelector('.multi-select-label');
    
    if (selected.length === 0) {
      labelEl.textContent = allLabel;
    } else if (selected.length === totalOptions) {
      labelEl.textContent = allLabel;
    } else if (selected.length <= 2) {
      labelEl.textContent = selected.join(', ');
    } else {
      labelEl.textContent = selected.length + ' selected';
    }
  }

  function getFilteredTasks() {
    var phaseVals = getSelectedValues(dom.phaseFilter);
    var statusVals = getSelectedValues(dom.statusFilter);
    var typeVals = getSelectedValues(dom.typeFilter);
    var ownerVals = getSelectedValues(dom.ownerFilter);
    return allTasks.filter(function(t) {
      if (phaseVals.length > 0 && phaseVals.indexOf(t.phase) === -1) return false;
      if (statusVals.length > 0 && statusVals.indexOf(t.status) === -1) return false;
      if (typeVals.length > 0 && typeVals.indexOf(t.type) === -1) return false;
      if (ownerVals.length > 0 && ownerVals.indexOf(t.owner) === -1) return false;
      return true;
    });
  }

  function renderStats() {
    var total = allTasks.length;
    var done = allTasks.filter(function(t) { return t.status.toLowerCase() === 'done'; }).length;
    var inProgress = allTasks.filter(function(t) { return t.status.toLowerCase() === 'in progress'; }).length;
    var pct = total > 0 ? Math.round((done / total) * 100) : 0;
    dom.headerStats.innerHTML =
      '<div class="stat-chip done"><span>Done</span><span class="stat-value">' + done + '/' + total + '</span></div>' +
      '<div class="stat-chip progress"><span>In Progress</span><span class="stat-value">' + inProgress + '</span></div>' +
      '<div class="stat-chip"><span>Progress</span><span class="stat-value">' + pct + '%</span></div>';
  }

  function renderKeyDates() {
    dom.keyDates.innerHTML = keyDatesData.map(function(kd) {
      return '<div class="key-date-card">' +
        '<span class="kd-label">' + kd.label + '</span>' +
        '<span class="kd-value">' + fmtDate(kd.date) + '</span>' +
        '<span class="kd-relative">' + relativeTime(kd.date) + '</span>' +
      '</div>';
    }).join('');
  }

  function renderPhaseFilter() {
    phases = [];
    var seen = {};
    allTasks.forEach(function(t) {
      if (!seen[t.phase]) { seen[t.phase] = true; phases.push(t.phase); }
    });
    
    var dropdown = dom.phaseFilter.querySelector('.multi-select-dropdown');
    var isInitialLoad = dropdown.children.length === 0;
    var currentSelected = getSelectedValues(dom.phaseFilter);
    
    var allChecked = isInitialLoad || currentSelected.length === phases.length;
    var html = '<label class="multi-select-option select-all-option">' +
      '<input type="checkbox" value="__all__"' + (allChecked ? ' checked' : '') + ' />' +
      '<span class="checkbox-custom"></span>All' +
      '</label>';

    html += phases.map(function(p) {
      var isChecked = isInitialLoad || currentSelected.indexOf(p) !== -1;
      return '<label class="multi-select-option">' +
        '<input type="checkbox" value="' + p + '"' + (isChecked ? ' checked' : '') + ' />' +
        '<span class="checkbox-custom"></span>' + p +
        '</label>';
    }).join('');
    
    dropdown.innerHTML = html;
    // Re-attach checkbox listeners only (trigger is set up once in setupEvents)
    setupMultiSelectCheckboxes(dom.phaseFilter, 'All Phases');
    updateMultiSelectLabel(dom.phaseFilter, 'All Phases');
  }

  function renderOwnerFilter() {
    var owners = [];
    var seen = {};
    allTasks.forEach(function(t) {
      if (t.owner && !seen[t.owner]) { seen[t.owner] = true; owners.push(t.owner); }
    });
    
    var dropdown = dom.ownerFilter.querySelector('.multi-select-dropdown');
    var isInitialLoad = dropdown.children.length === 0;
    var currentSelected = getSelectedValues(dom.ownerFilter);
    
    var allChecked = isInitialLoad || currentSelected.length === owners.length;
    var html = '<label class="multi-select-option select-all-option">' +
      '<input type="checkbox" value="__all__"' + (allChecked ? ' checked' : '') + ' />' +
      '<span class="checkbox-custom"></span>All' +
      '</label>';

    html += owners.map(function(o) {
      var isChecked = isInitialLoad || currentSelected.indexOf(o) !== -1;
      return '<label class="multi-select-option">' +
        '<input type="checkbox" value="' + o + '"' + (isChecked ? ' checked' : '') + ' />' +
        '<span class="checkbox-custom"></span>' + o +
        '</label>';
    }).join('');
    
    dropdown.innerHTML = html;
    setupMultiSelectCheckboxes(dom.ownerFilter, 'All Owners');
    updateMultiSelectLabel(dom.ownerFilter, 'All Owners');
  }

  function renderTimelineHeader(monthCols, currentMonthIdx) {
    var monthW = getMonthWidth();
    var totalW = monthCols.length * monthW;
    dom.timelineHeader.style.minWidth = totalW + 'px';
    dom.timelineHeader.innerHTML = monthCols.map(function(c, i) {
      return '<div class="month-header ' + (i === currentMonthIdx ? 'current-month' : '') + '">' +
        '<span class="month-label">' + c.label + '</span>' +
        "<span class=\"year-label\">'" + c.yearLabel + '</span>' +
      '</div>';
    }).join('');
  }

  function getMonthWidth() {
    return parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--month-w')) || 60;
  }

  function renderTasksAndBars(tasks, monthCols, currentMonthIdx) {
    dom.taskPanelBody.innerHTML = '';
    dom.timelineBody.innerHTML = '';
    var totalMonths = monthCols.length;
    var monthW = getMonthWidth();
    var totalTimelineW = totalMonths * monthW;
    var lastPhase = '';

    tasks.forEach(function(task, idx) {
      var animDelay = 'animation-delay: ' + (idx * 20) + 'ms;';

      if (task.phase !== lastPhase) {
        lastPhase = task.phase;
        var pIdx = phaseIndex(task.phase);
        var phEl = document.createElement('div');
        phEl.className = 'phase-header phase-' + pIdx;
        phEl.style.cssText = animDelay;
        phEl.textContent = task.phase;
        dom.taskPanelBody.appendChild(phEl);

        var tlPhEl = document.createElement('div');
        tlPhEl.className = 'timeline-phase-row';
        tlPhEl.style.cssText = 'min-width:' + totalTimelineW + 'px;' + animDelay;
        for (var i = 0; i < totalMonths; i++) {
          var cell = document.createElement('div');
          cell.className = 'timeline-cell' + (i === currentMonthIdx ? ' current-month-col' : '');
          tlPhEl.appendChild(cell);
        }
        dom.timelineBody.appendChild(tlPhEl);
      }

      var highlight = getHighlightClass(task);
      var trEl = document.createElement('div');
      trEl.className = 'task-row' + (highlight ? ' ' + highlight : '');
      trEl.style.cssText = animDelay;
      trEl.dataset.taskId = task.id;
      trEl.innerHTML =
        '<div class="tp-cell tp-id">' + task.id + '</div>' +
        '<div class="tp-cell tp-task" title="' + task.task.replace(/"/g, '&quot;') + '">' + task.task + '</div>' +
        '<div class="tp-cell tp-type">' + typeBadge(task.type) + '</div>' +
        '<div class="tp-cell tp-status">' + statusBadge(task.status) + '</div>' +
        '<div class="tp-cell tp-owner">' + task.owner + '</div>';
      dom.taskPanelBody.appendChild(trEl);

      var tlRowEl = document.createElement('div');
      tlRowEl.className = 'timeline-row';
      tlRowEl.style.cssText = 'min-width:' + totalTimelineW + 'px;' + animDelay;
      for (var j = 0; j < totalMonths; j++) {
        var tcell = document.createElement('div');
        tcell.className = 'timeline-cell' + (j === currentMonthIdx ? ' current-month-col' : '');
        tlRowEl.appendChild(tcell);
      }

      var barClass = getBarClass(task);
      var sharedClass = isSharedOwner(task.owner) ? ' bar-shared-owner' : '';
      
      var barLeft = 0;
      var barWidth = monthW;
      if (task.startDate && task.endDate) {
        barLeft = getDateXPos(task.startDate, monthCols, monthW);
        var barRight = getDateXPos(task.endDate, monthCols, monthW);
        barWidth = Math.max(barRight - barLeft, 2); // Minimum 2px width
      } else {
        var startCol = task.startM - 1;
        var endCol = task.endM;
        barLeft = startCol * monthW;
        barWidth = (endCol - startCol) * monthW;
      }

      if (task.type === 'Milestone') {
        var bar = document.createElement('div');
        bar.className = 'gantt-bar bar-milestone ' + barClass + sharedClass;
        bar.style.left = (barLeft - 11) + 'px';
        bar.style.cssText += animDelay;
        bar.innerHTML = '<div class="bar-fill"></div>';
        bar.addEventListener('mouseenter', function(e) { showTooltip(e, task); });
        bar.addEventListener('mouseleave', hideTooltip);
        bar.addEventListener('mousemove', moveTooltip);
        tlRowEl.appendChild(bar);
      } else {
        var bar2 = document.createElement('div');
        bar2.className = 'gantt-bar ' + barClass + sharedClass;
        bar2.style.left = barLeft + 'px';
        bar2.style.width = Math.max(barWidth, monthW/3) + 'px'; // Minimum visual width
        bar2.style.cssText += animDelay;
        var labelHtml = barWidth > monthW * 1.5 ? '<span class="bar-label">' + task.task + '</span>' : '';
        bar2.innerHTML = '<div class="bar-fill" style="width: 100%;"></div>' + labelHtml;
        bar2.addEventListener('mouseenter', function(e) { showTooltip(e, task); });
        bar2.addEventListener('mouseleave', hideTooltip);
        bar2.addEventListener('mousemove', moveTooltip);
        tlRowEl.appendChild(bar2);
      }

      dom.timelineBody.appendChild(tlRowEl);
    });
  }

  function renderTodayLine(monthCols) {
    dom.timelineBody.querySelectorAll('.today-line').forEach(function(el) { el.remove(); });
    var now = new Date();
    var monthW = getMonthWidth();
    var xPos = getDateXPos(now, monthCols, monthW);
    
    if (xPos >= 0 && xPos <= monthCols.length * monthW) {
      var line = document.createElement('div');
      line.className = 'today-line';
      line.style.left = xPos + 'px';
      dom.timelineBody.appendChild(line);
    }
  }

  // ---- Tooltip ----

  function showTooltip(e, task) {
    var urgent = isDueLessThanOneMonth(task.endDate);
    var daysLeft = task.endDate ? daysBetween(new Date(), task.endDate) : null;
    var daysStr = '';
    if (daysLeft !== null) {
      var daysText = daysLeft < 0 ? Math.abs(daysLeft) + ' days overdue' : daysLeft + ' days';
      var daysColor = urgent ? 'var(--clr-not-started-urgent)' : 'var(--clr-text)';
      daysStr = '<div class="tt-row"><span class="tt-label">Days left</span><span class="tt-value" style="color: ' + daysColor + '">' + daysText + '</span></div>';
    }
    var notesStr = task.notes ? '<div class="tt-notes">' + task.notes + '</div>' : '';
    dom.tooltip.innerHTML =
      '<div class="tt-title">' + task.task + '</div>' +
      '<div class="tt-row"><span class="tt-label">ID</span><span class="tt-value">' + task.id + '</span></div>' +
      '<div class="tt-row"><span class="tt-label">Phase</span><span class="tt-value">' + task.phase + '</span></div>' +
      '<div class="tt-row"><span class="tt-label">Type</span><span class="tt-value">' + task.type + '</span></div>' +
      '<div class="tt-row"><span class="tt-label">Status</span><span class="tt-value">' + statusBadge(task.status) + '</span></div>' +
      '<div class="tt-row"><span class="tt-label">Start</span><span class="tt-value">' + fmtDate(task.startDate) + ' (M' + task.startM + ')</span></div>' +
      '<div class="tt-row"><span class="tt-label">Due</span><span class="tt-value">' + fmtDate(task.endDate) + ' (M' + task.endM + ')</span></div>' +
      '<div class="tt-row"><span class="tt-label">Owner</span><span class="tt-value">' + task.owner + '</span></div>' +
      daysStr + notesStr;
    dom.tooltip.classList.remove('hidden');
    moveTooltip(e);
  }

  function moveTooltip(e) {
    var pad = 16;
    var ttRect = dom.tooltip.getBoundingClientRect();
    var x = e.clientX + pad;
    var y = e.clientY + pad;
    if (x + ttRect.width > window.innerWidth - pad) x = e.clientX - ttRect.width - pad;
    if (y + ttRect.height > window.innerHeight - pad) y = e.clientY - ttRect.height - pad;
    dom.tooltip.style.left = x + 'px';
    dom.tooltip.style.top = y + 'px';
  }

  function hideTooltip() {
    dom.tooltip.classList.add('hidden');
  }

  // ---- Event listeners ----

  function setupMultiSelectTrigger(multiSelectEl) {
    var trigger = multiSelectEl.querySelector('.multi-select-trigger');
    trigger.addEventListener('click', function(e) {
      e.stopPropagation();
      // Close other open multi-selects
      document.querySelectorAll('.multi-select.open').forEach(function(ms) {
        if (ms !== multiSelectEl) ms.classList.remove('open');
      });
      multiSelectEl.classList.toggle('open');
    });

    // Prevent dropdown clicks from closing
    var dropdown = multiSelectEl.querySelector('.multi-select-dropdown');
    dropdown.addEventListener('click', function(e) {
      e.stopPropagation();
    });
  }

  function setupMultiSelectCheckboxes(multiSelectEl, allLabel) {
    var checkboxes = multiSelectEl.querySelectorAll('input[type="checkbox"]');
    var allCheckbox = multiSelectEl.querySelector('input[value="__all__"]');

    checkboxes.forEach(function(cb) {
      cb.addEventListener('change', function(e) {
        if (cb === allCheckbox) {
          // If "All" is toggled, set all others to match its state
          var isChecked = cb.checked;
          checkboxes.forEach(function(otherCb) {
            if (otherCb !== cb) otherCb.checked = isChecked;
          });
        } else if (allCheckbox) {
          // If a normal option is toggled, update "All" state
          var allOthersChecked = true;
          var anyChecked = false;
          checkboxes.forEach(function(otherCb) {
            if (otherCb !== allCheckbox) {
              if (!otherCb.checked) allOthersChecked = false;
              if (otherCb.checked) anyChecked = true;
            }
          });
          
          if (!anyChecked) {
            // If everything is unchecked, optionally check "All" and all options if that's desired behavior
            // Based on request: "ubah phases ketika uncentang semua, value di phases jadi all phases, tetapi semua centang tidak perlu terpilih kembali semua sama seperti status dan type sekarang"
            // Wait, the request says: "ubah phases ketika uncentang semua, value di phases jadi all phases, tetapi semua centang tidak perlu terpilih kembali semua sama seperti status dan type sekarang."
            // This means when 0 items are checked, it acts as "All", but visually they stay unchecked. 
            // So we don't automatically check them. We just let it be 0 checked.
            allCheckbox.checked = false;
          } else {
             allCheckbox.checked = allOthersChecked;
          }
        }
        
        updateMultiSelectLabel(multiSelectEl, allLabel);
        render();
      });
    });
  }

  function setupMultiSelect(multiSelectEl, allLabel) {
    setupMultiSelectTrigger(multiSelectEl);
    setupMultiSelectCheckboxes(multiSelectEl, allLabel);
  }

  function setupEvents() {
    // Phase trigger set up once here; checkboxes re-attached in renderPhaseFilter()
    setupMultiSelectTrigger(dom.phaseFilter);
    setupMultiSelectTrigger(dom.ownerFilter);
    setupMultiSelect(dom.statusFilter, 'All Statuses');
    setupMultiSelect(dom.typeFilter, 'All Types');

    // Close dropdowns on outside click
    document.addEventListener('click', function() {
      document.querySelectorAll('.multi-select.open').forEach(function(ms) {
        ms.classList.remove('open');
      });
    });

    dom.refreshBtn.addEventListener('click', function() {
      dom.refreshBtn.classList.add('spinning');
      init().finally(function() { dom.refreshBtn.classList.remove('spinning'); });
    });
    dom.retryBtn.addEventListener('click', init);

    document.addEventListener('mouseover', function(e) {
      var row = e.target.closest('.task-row');
      if (row) {
        var children = Array.from(dom.taskPanelBody.children);
        var idx = children.indexOf(row);
        var tlRow = dom.timelineBody.children[idx];
        if (tlRow) tlRow.style.background = 'var(--clr-surface-2)';
      }
    });
    document.addEventListener('mouseout', function(e) {
      var row = e.target.closest('.task-row');
      if (row) {
        var children = Array.from(dom.taskPanelBody.children);
        var idx = children.indexOf(row);
        var tlRow = dom.timelineBody.children[idx];
        if (tlRow) tlRow.style.background = '';
      }
    });

    // Re-render on resize (handles mobile orientation changes / responsive --month-w)
    var resizeTimer;
    window.addEventListener('resize', function() {
      clearTimeout(resizeTimer);
      resizeTimer = setTimeout(function() {
        if (allTasks.length > 0) render();
      }, 200);
    });
  }

  function scrollToToday() {
    var todayLine = dom.timelineBody.querySelector('.today-line');
    if (todayLine) {
      var wrapper = $('#gantt-wrapper');
      var taskPanelW = $('#task-panel').offsetWidth;
      var lineLeft = parseFloat(todayLine.style.left) + taskPanelW;
      wrapper.scrollLeft = Math.max(0, lineLeft - wrapper.clientWidth / 2);
    }
  }

  // ---- Initialization ----

  async function init() {
    dom.loadingOverlay.classList.remove('hidden');
    dom.errorOverlay.classList.add('hidden');
    dom.app.classList.add('hidden');
    try {
      await loadData();
      dom.loadingOverlay.classList.add('hidden');
      dom.app.classList.remove('hidden');
      renderPhaseFilter();
      renderOwnerFilter();
      render();
      var now = new Date();
      dom.lastRefresh.textContent = fmtDate(now) + ' ' + now.toLocaleTimeString();
      setTimeout(scrollToToday, 300);
    } catch (err) {
      console.error('Failed to load timeline:', err);
      dom.loadingOverlay.classList.add('hidden');
      dom.errorOverlay.classList.remove('hidden');
      dom.errorMessage.textContent = err.message;
    }
  }

  setupEvents();
  init();
})();
